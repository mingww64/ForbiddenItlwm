// Byte patterns for /usr/sbin/bluetoothd, x86_64. The Tahoe build carries two sets, for macOS 26.7.1
// (25G241) and 26.7.3 (25G342); the Sequoia build (-DBTLEADV_SEQUOIA) carries one, from 15.8.3 (24H241) and matching 15.8 and 15.8.2,
// and the Sonoma build (-DBTLEADV_SONOMA) one, for 14.8.9 (23J631).
// Every set is tried on every page, and a set only matches its own build's bluetoothd. The four sites and the edits are the same on both; only the addresses,
// the vtable slots of the two capability queries and one struct offset differ.
//
// bluetoothd asks a controller about extended advertising and scanning only after
// chip-family checks that a third-party controller fails. LE_InitMultipleAdvertising
// then has no working route, so LE advertising never starts. These patches take the
// "supported" path. They don't touch the DisableExtAdvertising/DisableExtScans
// preferences, which can still turn the features off.
//
// Each pattern covers the failed-check branch, the call that fetches the chip object
// and the capability query, so a different bluetoothd build simply won't match.
